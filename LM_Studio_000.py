# Функция‑помощник: проверяем, является ли данное число простым.
def is_prime(x):
    """
    Возвращает True, если x – простое число; иначе False.

    Алгоритм:
        - Если x < 2 → не простое (для нашего случая это никогда не произойдет,
          но функция будет универсальной).
        - Проверяем делители от 2 до sqrt(x) включительно.
          Если найдётся делитель, возвращаем False.
        - Если ни один из делителей не найден – число простое.
    """
    if x < 2:
        return False

    # Идем только до квадратного корня из x (быстрее).
    limit = int(x ** 0.5) + 1
    for d in range(2, limit):
        if x % d == 0:          # найден делитель → число не простое
            return False
    return True                 # делителей нет → простое


def main():
    """
    Основная логика программы:
        1. Считываем ввод пользователя.
        2. Проверяем, что это целое число ≥ 2.
           Если ввод неверный – просим повторить.
        3. Генерируем список простых чисел от 2 до N (включительно).
        4. Печатаем их через пробел.
    """
    # Считываем строку с клавиатуры, удаляем возможные пробелы.
    n_input = input("Введите целое число N (≥ 2): ").strip()

    # Попробуем преобразовать строку в целое число и проверить диапазон.
    try:
        N = int(n_input)
        if N < 2:
            raise ValueError
    except ValueError:
        print("Ошибка: введено некорректное значение. "
              "Попробуйте снова.")
        return

    # Создаём список простых чисел с помощью list‑comprehension.
    primes = [num for num in range(2, N + 1) if is_prime(num)]

    # Формируем строку для вывода: числа через пробел.
    output = " ".join(str(p) for p in primes)
    print(f"Простые числа от 2 до {N}:")
    print(output)


# Запускаем программу, если файл выполняется как скрипт
if __name__ == "__main__":
    main()
